const SIN_INDICE: u8 = 255;

const INDICES: [u8; 256] = construir_indices();

const fn construir_indices() -> [u8; 256] {
    let mut indices = [SIN_INDICE; 256];
    let mut posicion = 0;
    while posicion < AMINOACIDOS.len() {
        let letra = AMINOACIDOS[posicion];
        indices[letra as usize] = posicion as u8;
        indices[letra.to_ascii_lowercase() as usize] = posicion as u8;
        posicion += 1;
    }
    indices
}

pub fn indice_aminoacido(aminoacido: u8) -> Option<usize> {
    match INDICES[aminoacido as usize] {
        SIN_INDICE => None,
        indice => Some(indice as usize),
    }
}

fn puntuar(matriz: &[[i32; 20]; 20], a: u8, b: u8, minimo: i32) -> i32 {
    match (indice_aminoacido(a), indice_aminoacido(b)) {
        (Some(i), Some(j)) => matriz[i][j],
        _ => minimo,
    }
}

pub fn blosum62(a: u8, b: u8) -> i32 {
    puntuar(&BLOSUM62, a, b, -4)
}

pub fn pam250(a: u8, b: u8) -> i32 {
    puntuar(&PAM250, a, b, -8)
}
